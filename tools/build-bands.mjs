/* Resolves every band tone to its real colour in each theme (from css/tokens.css) and writes:
   - builder/theme-colors.js  → lets the builder avoid two neighbouring bands that look the same in a theme
   - css/bands-themes.css     → per-theme fixes so titles and highlights on a band always have contrast
   Run after changing tokens or tones:  node tools/build-bands.mjs */
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('..', import.meta.url);
const css = await readFile(new URL('css/tokens.css', root), 'utf8');
const TONES = { cream: 'bg-hero-panel', sage: 'bg-quiz', sun: 'marquee-accent-bg', coral: 'accent-primary', pink: 'bg-promo-subtle', aqua: 'bg-brand-secondary', ink: 'bg-inverse' };
const THEMES = ['electric', 'submarine', 'salad', 'skittles', 'lego'];
const decls = block => Object.fromEntries([...block.matchAll(/--color-([a-z0-9-]+):\s*([^;]+);/g)].map(m => [m[1], m[2].trim()]));
const base = decls(css.slice(css.indexOf(':root'), css.indexOf('[data-theme="electric"]')));
const themed = t => { const i = css.indexOf(`[data-theme="${t}"] {`); return i < 0 ? {} : decls(css.slice(i, css.indexOf('}', i))); };
const resolve = (map, name, depth = 0) => { const v = map[name]; if (!v || depth > 8) return null; const m = v.match(/^var\(--color-([a-z0-9-]+)\)$/); return m ? resolve(map, m[1], depth + 1) : v; };
const lum = hex => { const c = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(v => v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const MIN = 2.4; // the brand's white-on-coral sits at ~2.6 and is an accepted exception; anything below this is not legible
const BIG = 2.5, SMALL = 4.5; // large display text may sit at the brand's white-on-coral level; anything smaller needs AA
const ALIAS = { 'k-mq-plain': 'marquee-plain-text', 'k-mq-accent': 'marquee-accent-text', 'k-promo': 'text-promo', 'k-brandtext': 'text-brand', 'k-ink': 'text-primary' };
const ref = n => ALIAS[n] ? `var(--${n})` : `var(--color-${n})`;
const colors = {}, rules = [];
for (const t of THEMES) {
  const map = { ...base, ...themed(t) }; colors[t] = {}; const hex = n => resolve(map, ALIAS[n] || n);
  for (const [tone, token] of Object.entries(TONES)) colors[t][tone] = resolve(map, token);
  for (const [tone, bg] of Object.entries(colors[t])) {
    const fgName = contrast(hex('k-ink'), bg) >= contrast(hex('text-inverse'), bg) ? 'k-ink' : 'text-inverse';
    const pick = (cands, min) => cands.find(c => hex(c) && contrast(hex(c), bg) >= min) || fgName;
    const large = ['k-mq-plain', 'k-mq-accent', 'k-promo', 'text-on-accent', 'bg-brand', 'accent-primary'];
    const first = { coral: 'text-on-accent', ink: 'accent-primary', sun: 'k-mq-accent' }[tone];
    const order = first ? [first, ...large.filter(c => c !== first)] : large;
    const out = [`--band-fg: ${ref(fgName)}`,
      `--band-title: ${ref(tone === 'coral' || tone === 'ink' ? pick(['text-on-accent'], BIG) : fgName)}`,
      `--band-accent: ${ref(['cream', 'sun', 'coral', 'ink'].includes(tone) ? pick(order, BIG) : fgName)}`,
      `--band-mark: ${ref(pick(order, BIG))}`,
      `--band-mark-2: ${ref(pick(['accent-secondary', ...order], SMALL))}`,
      `--band-link: ${ref(pick(['k-brandtext'], SMALL))}`];
    rules.push(`[data-theme="${t}"] .k-band--${tone}${t === 'electric' ? `, :root:not([data-theme]) .k-band--${tone}` : ''} { ${out.join('; ')}; }`);
  }
  colors[t].footer = resolve(map, 'bg-footer');
}
await writeFile(new URL('builder/theme-colors.js', root), `/* Generated by tools/build-bands.mjs — real colour of each band tone per theme. */\nexport const TONE_COLORS = ${JSON.stringify(colors, null, 1)};\n`);
await writeFile(new URL('css/bands-themes.css', root), `/* Generated by tools/build-bands.mjs — keeps band titles and highlights legible in every theme. Do not edit. */\n${rules.join('\n')}\n`);
